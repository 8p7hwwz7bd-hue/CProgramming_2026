#include <stdio.h>

int main(void)
{
    /*
     * -----------------------------------------------------------------
     * 【1. 変数の宣言と初期化 (Declarations and Initialization)】
     * -----------------------------------------------------------------
     * ・すべての変数は、プログラム内で使用する前に必ず宣言しなければなりません。
     * ・通常は、関数の最初（実行文が始まる前）にまとめて書きます。
     * ・宣言と同時に、初期値を入れる（初期化する）ことも可能です。
     */
    
    // まとめた宣言の例
    int lower, upper, step;
    
    // 個別の宣言と初期化の例
    char esc = '\\';       // バックスラッシュのエスケープ文字
    int i = 0;             // 0で初期化
    float eps = 1.0e-5;    // 指数表記を使った初期化（0.00001）

    printf("=== 1. Initialization Test ===\n");
    printf("i = %d, esc = %c, eps = %f\n\n", i, esc, eps);


    /*
     * -----------------------------------------------------------------
     * 【2. const 修飾子 (The const Qualifier)】
     * -----------------------------------------------------------------
     * ・変数に `const` をつけると、「後から値を絶対に変更できない（読み取り専用）」
     *   にすることができます。
     * ・もし後から値を書き換えようとすると、コンパイルエラーになり事故を防げます。
     */
    
    const double e = 2.71828182845905;  // ネイピア数（円周率のような定数）
    const char msg[] = "warning: ";      // 変更したくない文字列メッセージ

    printf("=== 2. Const Qualifier Test ===\n");
    printf("Mathematical constant e: %lf\n", e);
    printf("Message: %s\n", msg);

    /*
     * 【注意】
     * constがついた変数に再代入しようとするとエラーになります：
     * e = 3.14; // ← コンパイルエラー！ (Assignment of read-only variable 'e')
     */

    return 0;
}
