#include <stdio.h>

// プロトタイプ宣言
void squeeze(char s[], int c);

int main(void)
{
    /*
     * -----------------------------------------------------------------
     * 【2.5 算術演算子 & 2.6 関係・論理演算子】
     * -----------------------------------------------------------------
     * ・算術演算子: +, -, *, /, % (剰余・余り)
     * ・関係演算子: >, >=, <, <=, ==, !=
     * ・論理演算子: && (AND), || (OR), ! (NOT)
     * ・【重要】関係演算子や論理演算子は、算術演算子よりも優先順位が低いです。
     *   そのため「i < lim - 1」などは、括弧なしでも正しく評価されます。
     */
    int year = 2024;
    // うるう年（Leap year）の判定ロジック例
    if ((year % 4 == 0 && year % 100 != 0) || year % 400 == 0) {
        printf("%d is a leap year (うるう年)\n\n", year);
    }

    /*
     * -----------------------------------------------------------------
     * 【2.7 型変換 (Type Conversions)】
     * -----------------------------------------------------------------
     * ・暗黙の型変換 (Implicit): 代入時や計算時に自動で型が揃えられます。
     * ・明示的な型変換 (Explicit / キャスト): (型名) のように書いて強制的に変換します。
     */
    int n_val = 9;
    double root_val;
    
    // int型の n_val を一時的に double型 にキャストして平方根関数等に渡すイメージ
    // （ここでは擬似的に計算結果を出力）
    root_val = (double)n_val; 
    printf("=== Explicit Type Conversion ===\n");
    printf("int %d cast to double: %.1f\n\n", n_val, root_val);

    /*
     * -----------------------------------------------------------------
     * 【2.8 インクリメント・デクリメント演算子】
     * -----------------------------------------------------------------
     * ・++n (前置): まず値を1増やしてから、その式評価を行う
     * ・n++ (後置): 式を評価したあとに、値を1増やす
     * ・注意: 変数に対してのみ適用できます（(i+j)++ のような書き方はエラーになります）
     */
    int x = 5;
    int y = x++; // yには「増える前の5」が代入され、そのあとxが6になる（後置）
    printf("=== Increment Test ===\n");
    printf("After y = x++ -> x = %d, y = %d\n", x, y);
    
    x = 5;
    y = ++x; // xが6に増えてから、その「6」がyに代入される（前置）
    printf("After y = ++x -> x = %d, y = %d\n\n", x, y);


    /*
     * -----------------------------------------------------------------
     * 【2.9 ビット演算子 (Bitwise Operators)】
     * -----------------------------------------------------------------
     * ・&  : ビットごとの AND（マスク処理など、特定のビットを0にする）
     * ・|  : ビットごとの OR（特定のビットを1にする）
     * ・^  : ビットごとの排他的論理和 (XOR)
     * ・<< : 左シフト（値が大きくなる、4倍など）
     * ・>> : 右シフト
     * ・~  : 1の補数（ビット反転）
     */
    unsigned char bits_x = 037; // 8進数の 037 (2進数で 00011111)
    unsigned char masked = bits_x & 007; // 下位3ビット以外をマスク（0にする）
    printf("=== Bitwise Operator Test ===\n");
    printf("Masked result (octal): %o\n\n", masked);


    /*
     * -----------------------------------------------------------------
     * 【2.10 代入演算子と式 / 応用例: squeeze 関数】
     * -----------------------------------------------------------------
     * ・文字列から指定した文字をすべて取り除く関数のテスト
     */
    char text[] = "hello world!";
    printf("Before squeeze: %s\n", text);
    
    squeeze(text, 'o'); // 'o' の文字をすべて消す
    printf("After squeeze('o'): %s\n", text);

    return 0;
}

/* 
 * squeeze: 文字列 s から文字 c と一致するものをすべて削除する関数 
 */
void squeeze(char s[], int c)
{
    int i, j;

    for (i = j = 0; s[i] != '\0'; i++) {
        if (s[i] != c) {
            s[j++] = s[i];
        }
    }
    s[j] = '\0';
}
