int main(void)
{
    /*
     * -----------------------------------------------------------------
     * 【2.1 Variable Names（変数名に関するルール）】
     * -----------------------------------------------------------------
     * ・名前はアルファベット（文字）と数字で構成される。
     * ・先頭の文字は必ず「アルファベット」である必要がある（数字はNG）。
     * ・アンダーバー「_」も文字として扱え、長い変数名の可読性を上げるのに便利。
     * ・大文字と小文字は区別される（例: x と X は別の変数として扱われる）。
     * ・慣習として、変数名は小文字、記号定数（#define）はすべて大文字にする。
     * ・予約語（if, else, int, float など、C言語であらかじめ使われている言葉）は変数名に使えない。
     */
    
    // 良い変数名の例
    int student_age = 20;
    int max_score = 100;


    /*
     * -----------------------------------------------------------------
     * 【2.2 Data Types and Sizes（データ型とサイズ）】
     * -----------------------------------------------------------------
     * C言語の基本的なデータ型と、一般的なサイズ（バイト数）のメモ：
     *   - char   : 1バイト（1文字を保持できる）
     *   - short  : 短い整数
     *   - int    : 通常の整数（ホストマシンの自然なサイズを反映）
     *   - long   : 長い整数
     *   - float  : 単精度浮動小数点数（小数の計算）
     *   - double : 倍精度浮動小数点数（より精度の高い小数の計算）
     *
     * 【Type Qualifiers（型修飾子 / modifier）】
     *   - short / long : データの大きさを調整する
     *   - signed / unsigned : 符号付き（プラスマイナス両方）か、
     *                         符号なし（常にプラス、範囲が倍になる）かを指定する
     */

    // Exercise 2-1: 実際に sizeof 演算子を使って、現在の環境でのサイズを確認するコード
    printf("=== Exercise 2-1: Data Type Sizes on this Machine ===\n");
    
    printf("char   size = %lu byte(s)\n", sizeof(char));
    printf("short  size = %lu byte(s)\n", sizeof(short));
    printf("int    size = %lu byte(s)\n", sizeof(int));
    printf("long   size = %lu byte(s)\n", sizeof(long));
    printf("float  size = %lu byte(s)\n", sizeof(float));
    printf("double size = %lu byte(s)\n", sizeof(double));

    return 0;
}