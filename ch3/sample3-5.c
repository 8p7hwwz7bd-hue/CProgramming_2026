#include <stdio.h>

int main(void)
{
    /*
     * -----------------------------------------------------------------
     * 【1. While ループの基本】
     * -----------------------------------------------------------------
     * ・条件式 (expression) が真（非ゼロ）の間、ずっと中の文が実行され続けます。
     * ・条件が偽（ゼロ）になるとループを抜けます。
     */
    printf("=== 1. While Loop Test ===\n");
    int i = 0;
    while (i < 3) {
        printf("while i = %d\n", i);
        i++; // ループを抜けるためのインクリメント
    }


    /*
     * -----------------------------------------------------------------
     * 【2. For ループと While ループの等価性】
     * -----------------------------------------------------------------
     * スライドにもある通り、以下の for 文：
     *   for (expr1; expr2; expr3) { statement; }
     * は、以下の while 文の書き方にそっくりそのまま置き換えることができます[cite: 25]：
     *
     *   expr1;
     *   while (expr2) {
     *       statement;
     *       expr3;
     *   }
     */
    printf("\n=== 2. For Loop Test (Equivalent to While) ===\n");
    // 上記のwhileの形をそのままfor文でスマートに書いたもの
    for (int j = 0; j < 3; j++) {
        printf("for j = %d\n", j);
    }


    /*
     * -----------------------------------------------------------------
     * 【3. 無限ループ (Infinite Loop)】
     * -----------------------------------------------------------------
     * ・for文の「初期化・条件・増減」の3つの要素をすべて省略すると、
     *   条件判定が常に「真（true）」とみなされ、無限ループになります[cite: 25]。
     *   （※実際のプログラムでは意図しない限り暴走するので注意！）
     * 
     * 記述例（コメントアウトしています）：
     *   for ( ; ; ) {
     *       // ずっと繰り返される処理
     *   }
     */


    /*
     * -----------------------------------------------------------------
     * 【4. while と for の使い分けの基準】
     * -----------------------------------------------------------------
     * ・どちらを使うかは基本的には個人の好み（personal preference）です[cite: 25]。
     * ・ただし：
     *   - 特殊な初期化やインクリメントが不要なループは `while` の方が自然[cite: 25]。
     *   - 「初期化」「条件判定」「カウンタの増減」を1箇所にまとめてすっきり
     *     管理したいときは `for` の方がバグを防ぎやすく好ましいです[cite: 25]。
     */

    return 0;
}