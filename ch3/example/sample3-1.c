#include <stdio.h>

int main(void)
{
    /*
     * -----------------------------------------------------------------
     * 【1. 式から文へ (Statements)】
     * -----------------------------------------------------------------
     * ・「x = 0」や「i++」、「printf(...)」といった「式」のあとに
     *   セミコロン「;」をつけることで、C言語の「文（Statement）」になります。
     * ・セミコロンは文の「区切り文字（セパレーター）」ではなく、
     *   文の「終わりを示す目印（ターミネーター）」です。
     */
    int x = 0;
    int i = 0;

    x = 5;  // 文
    i++;    // 文
    printf("Initial x = %d, i = %d\n\n", x, i);


    /*
     * -----------------------------------------------------------------
     * 【2. ブロック / 複合文 (Block, Compound statement)】
     * -----------------------------------------------------------------
     * ・中括弧 `{` と `}` で囲まれたまとまりを「ブロック」または「複合文」と呼びます。
     * ・ブロックは、文法的には「1つの文」と同じ扱いになります。
     * ・主に、関数のなかや、if・while・forなどの制御構文の後ろで、
     *   複数の文をひとまとめにして実行したいときに使います。
     */
    
    // ブロックを使ったまとまりの例
    {
        int temp = 10; // ブロックの中で新しい変数を宣言することも可能
        x += temp;
        printf("Inside block: x = %d\n", x);
    } // ← ここでブロックが終わり、temp変数は消滅する

    // for文やif文と組み合わせる例
    for (i = 0; i < 3; i++) {
        // この `{` から `}` の中身がひとつのブロック（複合文）
        printf("Loop count: %d\n", i);
    }

    return 0;
}
