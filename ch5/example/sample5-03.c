#include <stdio.h>

int main(void)
{
    /*
     * -----------------------------------------------------------------
     * 【1. 配列とポインタの基本関係】
     * -----------------------------------------------------------------
     * ・int a[10]; は、メモリ上に 10個の連続した整数領域を確保します。
     * ・配列名 a は、その「先頭要素のアドレス（&a[0]）」を意味しています。
     */
    int a[5] = {10, 20, 30, 40, 50};
    int *pa;

    pa = &a[0]; // pa に配列の先頭（0番目）のアドレスを代入（単に pa = a; と書いても同じです）

    printf("=== 1. Array and Pointer Basics ===\n");
    printf("Address of a[0] (&a[0]): %p\n", (void *)&a[0]);
    printf("Value of pa            : %p\n", (void *)pa);
    printf("Value pointed by *pa   : %d\n\n", *pa); // 10 が表示される


    /*
     * -----------------------------------------------------------------
     * 【2. 添字表記とポインタ演算子の等価性】
     * -----------------------------------------------------------------
     * ・スライドにある通り、以下の表現は完全に同じ意味になります：
     *   a[i]  ⇔  *(pa + i)
     * ・pa が先頭を指しているとき、pa + i は「i個先の要素のアドレス」を表し、
     *   そこに * をつけることでその中身を取り出すことができます。
     */
    printf("=== 2. Accessing Elements via Pointers ===\n");
    for (int i = 0; i < 5; i++) {
        // 以下の3つの書き方は、すべて全く同じ値（配列の要素）を指しています！
        printf("a[%d] = %d  |  *(pa + %d) = %d  |  *(a + %d) = %d\n", 
               i, a[i], 
               i, *(pa + i), 
               i, *(a + i));
    }

    return 0;
}
