#include <stdio.h>

int main(void)
{
    /*
     * -----------------------------------------------------------------
     * 【1. ポインタの基本概念】
     * -----------------------------------------------------------------
     * ・ポインタ (Pointer) は、「変数のメモリー上の住所（アドレス）」を格納する変数です。
     * ・& (アドレス演算子) : 変数の「住所」を取得する (例: &x)
     * ・* (間接参照演算子) : ポインタが指す住所の先にある「中身（値）」にアクセスする
     */
    int x = 1, y = 2, z[10];
    int *ip;        /* ip は int型へのポインタ変数宣言 */

    ip = &x;        /* ip に x のアドレスを代入する（ip は x を指す） */
    y = *ip;        /* ip が指す先の中身（つまり x の値 1）を y に代入する (*ip は dereferencing) */
    *ip = 0;        /* ip が指す先の中身を 0 に書き換える（つまり x が 0 になる） */
    ip = &z[0];     /* ip は配列 z の先頭要素のアドレスを指すようになる */

    printf("=== 1. Basic Pointer Test ===\n");
    printf("x = %d, y = %d, *ip (z[0]) = %d\n\n", x, y, *ip);


    /*
     * -----------------------------------------------------------------
     * 【2. スライドのトレース演習 (Trace Exercise)】
     * -----------------------------------------------------------------
     * スライド5ページ下部にある、変数の変化を追うプログラムの実行例です。
     */
    printf("=== 2. Trace Exercise Result ===\n");
    
    int m = 10, n = 5;
    int *mp, *np;

    mp = &m;  /* mp は m を指す (mp が指す値は 10) */
    np = &n;  /* np は n を指す (np が指す値は 5) */

    *mp = *mp + *np;  /* m の値が 10 + 5 = 15 に変わる (*mpも15) */
    *np = *mp - *np;  /* n の値が 15 - 5 = 10 に変わる (*npも10) */

    /* 
     * 最終的な変数の値と、ポインタ経由で覗いた値を出力する
     * 答えの予測：m = 15, n = 10, *mp = 15, *np = 10
     */
    printf("m = %d, n = %d, *mp = %d, *np = %d\n", m, n, *mp, *np);

    return 0;
}
